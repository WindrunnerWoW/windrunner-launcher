using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace WindrunnerLauncher.Core.Hearthstone;

/// <summary>
/// Writes the Lua lists that tell the addon which textures exist (the launcher-side port of the generating half of
/// the module's tools/deploy/deploy-addon.ps1): CardTextures.lua (cards, minions, powers, heroes), BoardTextures.lua,
/// CollectionTextures.lua and Battlegrounds\BgTextures.lua. The addon ships these as empty placeholders, and
/// without the real lists it falls back to the plain WoW look.
///
/// A texture is listed when its .blp is in the built texture folder and the module's manifest knows it.
/// The files are written as loose files into Interface\AddOns\Hearthstone, which the client prefers over the patch.
/// </summary>
public static class HearthstoneLuaLists
{
    private const string TexturePath = "Interface\\\\Hearthstone\\\\Textures\\\\";
    private const int CollectionMaxSide = 512;

    /// <summary>The generated files: path relative to Interface\AddOns\Hearthstone (forward slashes) -> content.</summary>
    public static Dictionary<string, string> Generate(HearthstoneArtInputs inputs, string textureRoot, List<string>? warnings = null)
    {
        var files = new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["CardTextures.lua"] = CardTextures(inputs, textureRoot, warnings),
            ["Battlegrounds/BgTextures.lua"] = BgTextures(inputs, textureRoot, warnings),
        };
        if (BoardTextures(inputs, textureRoot, warnings) is { } board)
            files["BoardTextures.lua"] = board;
        if (CollectionTextures(inputs, textureRoot, warnings) is { } collection)
            files["CollectionTextures.lua"] = collection;
        return files;
    }

    /// <summary>Writes the files below the addon folder: LF line ends, no BOM, like the PowerShell original.</summary>
    public static void Write(string addonFolder, IReadOnlyDictionary<string, string> files)
    {
        var utf8 = new UTF8Encoding(false);
        foreach (var (rel, content) in files)
        {
            var path = Path.Combine(addonFolder, rel.Replace('/', Path.DirectorySeparatorChar));
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, content, utf8);
        }
    }

    // ---- CardTextures.lua

    private static string CardTextures(HearthstoneArtInputs inputs, string root, List<string>? warnings)
    {
        var entries = inputs.Read(HearthstoneArtInputs.TexturesManifest)["entries"]!.AsObject();
        var cards = Installed(root, "Cards", entries, warnings, "textures.manifest.json");
        var minions = Installed(root, "Minions", inputs.Minions, warnings, "minions.manifest.json");
        var powers = Installed(root, "Powers", inputs.Powers, warnings, "powers.manifest.json");
        var heroes = Installed(root, "Heroes", inputs.HeroSkins, warnings, "hero_skins.manifest.json");

        var sb = new StringBuilder();
        sb.Append("-- GENERATED by the Windrunner launcher from the Hearthstone module's data/art manifests.\n");
        sb.Append("-- Do not edit. Lists the textures in Interface\\Hearthstone\\Textures (browse order and bottom texcoord).\n");
        sb.Append("-- Lua 5.0 (WoW 1.12).\n\n");
        sb.Append($"HS_CardTextures = {{\n    generated = true,\n    mode = \"All\",\n    count = {cards.Count},\n    order = {{\n");
        Chunks(sb, cards.Select(Quote), 6);
        sb.Append("    },\n    bottom = {\n");
        foreach (var id in cards)
            sb.Append($"        [\"{id}\"] = {Num(entries[id]!["texcoord"]!["bottom"]!)},\n");
        sb.Append("    },\n}\n");

        sb.Append("\n-- Oval minion portraits (Textures\\Minions\\<id>.blp): the ids that exist.\n");
        sb.Append($"HS_MinionTextures = {{\n    generated = true,\n    count = {minions.Count},\n    set = {{\n");
        Chunks(sb, minions.Select(SetEntry), 4);
        sb.Append("    },\n}\n");

        sb.Append("\n-- Round hero power portraits (Textures\\Powers\\<id>.blp): the ids that exist.\n");
        sb.Append($"HS_PowerTextures = {{\n    generated = true,\n    count = {powers.Count},\n    set = {{\n");
        Chunks(sb, powers.Select(SetEntry), 4);
        sb.Append("    },\n}\n");

        sb.Append("\n-- Alternative hero portraits (Textures\\Heroes\\<id>.blp): id -> texcoord bottom.\n");
        sb.Append($"HS_HeroTextures = {{\n    generated = true,\n    count = {heroes.Count},\n    set = {{\n");
        foreach (var id in heroes)
            sb.Append($"        [\"{id}\"] = {Num(inputs.HeroSkins[id]!["texcoord"]!["bottom"]!)},\n");
        sb.Append("    },\n}\n");
        return sb.ToString();
    }

    // ---- Battlegrounds\BgTextures.lua

    private static string BgTextures(HearthstoneArtInputs inputs, string root, List<string>? warnings)
    {
        var bgMinions = inputs.BgMinions;
        var bgHeroes = inputs.BgHeroes;
        var bgQuests = inputs.BgQuests;

        var minionIds = Installed(root, "BgMinions", bgMinions["entries"]!.AsObject(), warnings, "bg_minions.manifest.json");
        var cardKeys = Installed(root, "BgMinions/Cards", bgMinions["cards"]?.AsObject(), null, null);
        var heroKeys = Installed(root, "BgHeroes", bgHeroes["entries"]!.AsObject(), null, null);
        var powerKeys = Installed(root, "BgHeroes/Powers", bgHeroes["powers"]?.AsObject(), null, null);
        var powerCardKeys = Installed(root, "BgHeroes/PowerCards", bgHeroes["powerCards"]?.AsObject(), null, null);

        var questEntries = bgQuests["entries"]!.AsObject();
        var questInstalled = Installed(root, "BgQuests", questEntries, warnings, "bg_quests.manifest.json");
        var questKeys = questInstalled.Where(k => Group(questEntries[k]) == "quest").ToList();
        var rewardKeys = questInstalled.Where(k => Group(questEntries[k]) == "reward").ToList();
        var rewardCards = bgQuests["cards"]?.AsObject();
        var rewardCardKeys = Installed(root, "BgQuests/Cards", rewardCards, null, null);
        var rewardBaked = rewardCardKeys.Where(k => rewardCards![k]?["baked"]?.GetValue<bool>() == true).ToList();

        var sb = new StringBuilder();
        sb.Append("-- GENERATED by the Windrunner launcher from the Hearthstone module's bg_minions, bg_heroes and bg_quests manifests.\n");
        sb.Append("-- Do not edit. Lists the Battlegrounds textures in Interface\\Hearthstone\\Textures; the addon's\n");
        sb.Append("-- Battlegrounds tiles fall back to the text tile for an id that is not listed. A golden minion\n");
        sb.Append("-- uses its normal twin's portrait; the gold ring is Textures\\Bg\\golden_ring.blp.\n");
        sb.Append("-- Lua 5.0 (WoW 1.12).\n\n");
        sb.Append($"HS_BgTextures = {{\n    generated = true,\n    count = {minionIds.Count},\n    set = {{\n");
        Chunks(sb, minionIds.Select(SetEntry), 4);
        sb.Append("    },\n    cards = {          -- Textures\\BgMinions\\Cards\\<cardId> full cards (256x512, card in the top 388 rows) of the hover, golden twins too\n");
        Chunks(sb, cardKeys.Select(SetEntry), 4);
        sb.Append("    },\n");
        sb.Append($"    heroes = {{{List(heroKeys)}}},          -- Textures\\BgHeroes\\<heroId>: Bob's arch and the lobby portraits\n");
        sb.Append($"    powers = {{{List(powerKeys)}}},          -- Textures\\BgHeroes\\Powers\\<powerId> round portraits shown in the hero power button\n");
        sb.Append($"    powerCards = {{{List(powerCardKeys)}}},          -- Textures\\BgHeroes\\PowerCards\\<powerId> full hero power cards of the hero pick's hover\n");
        sb.Append($"    quests = {{{List(questKeys)}}},          -- Textures\\BgQuests\\<questId> round portraits of the in-pool 24.2 quests\n");
        sb.Append($"    rewards = {{{List(rewardKeys)}}},          -- Textures\\BgQuests\\<rewardId> round portraits of the in-pool 24.2 rewards\n");
        sb.Append($"    rewardBaked = {{{List(rewardBaked)}}},          -- the rewardCards baked from the real frame (art but no words): the quest pick writes their name and text\n");
        sb.Append($"    rewardCards = {{{List(rewardCardKeys)}}},          -- Textures\\BgQuests\\Cards\\<rewardId> full reward cards of the quest pick\n}}\n");
        return sb.ToString();
    }

    // ---- BoardTextures.lua

    private static string? BoardTextures(HearthstoneArtInputs inputs, string root, List<string>? warnings)
    {
        var pieces = inputs.Board["pieces"]!.AsObject();
        var names = Installed(root, "Board", pieces, warnings, "board_textures.manifest.json");
        if (names.Count == 0)
            return null;

        var sb = new StringBuilder();
        sb.Append("-- GENERATED by the Windrunner launcher from data/art/board_textures.manifest.json.\n");
        sb.Append("-- Do not edit. Lists the pieces in Textures\\Board: path, w/h (used pixels), right/bottom\n");
        sb.Append("-- (SetTexCoord(0, right, 0, bottom)), anchors as fractions of the used image, aspect for stretched pieces.\n");
        sb.Append("-- Lua 5.0 (WoW 1.12).\n\n");
        sb.Append("HS_BoardTextures = {\n    generated = true,\n    pieces = {\n");
        foreach (var n in names)
        {
            var e = pieces[n]!;
            var line = new StringBuilder(
                $"        {n} = {{ path = \"{TexturePath}Board\\\\{n}\", w = {Num(e["w"]!)}, h = {Num(e["h"]!)}, right = {Num(e["right"]!)}, bottom = {Num(e["bottom"]!)}");
            if (e["aspect"] is { } aspect)
                line.Append($", aspect = {Num(aspect)}");
            if (e["anchors"] is JsonObject { Count: > 0 } anchors)
            {
                var parts = anchors.OrderBy(a => a.Key, StringComparer.Ordinal).Select(a =>
                    $"{a.Key} = {{ left = {Num(a.Value!["left"]!)}, top = {Num(a.Value!["top"]!)}, right = {Num(a.Value!["right"]!)}, bottom = {Num(a.Value!["bottom"]!)} }}");
                line.Append($", anchors = {{ {string.Join(", ", parts)} }}");
            }

            sb.Append(line).Append(" },\n");
        }

        sb.Append("    },\n}\n");
        return sb.ToString();
    }

    // ---- CollectionTextures.lua

    private static string? CollectionTextures(HearthstoneArtInputs inputs, string root, List<string>? warnings)
    {
        var pieces = inputs.Read(HearthstoneArtInputs.CollectionManifest)["pieces"]!.AsObject();
        var names = Installed(root, "Collection", pieces, warnings, "collection_textures.manifest.json");
        if (names.Count == 0)
            return null;

        // the 1.12 client does not load a texture side above 512 (it draws solid green)
        foreach (var n in names)
        {
            if (pieces[n]!["texture_size"] is JsonArray { Count: 2 } size
                && (size[0]!.GetValue<int>() > CollectionMaxSide || size[1]!.GetValue<int>() > CollectionMaxSide))
                throw new InvalidDataException($"Collection/{n}.blp is {size[0]}x{size[1]}: the client does not load textures above {CollectionMaxSide} pixels.");
        }

        var sb = new StringBuilder();
        sb.Append("-- GENERATED by the Windrunner launcher from data/art/collection_textures.manifest.json.\n");
        sb.Append("-- Do not edit. Lists the pieces in Textures\\Collection: path, w/h (used pixels), right/bottom\n");
        sb.Append("-- (SetTexCoord(0, right, 0, bottom)).\n");
        sb.Append("-- Lua 5.0 (WoW 1.12).\n\n");
        sb.Append("HS_CollectionTextures = {\n    generated = true,\n    pieces = {\n");
        foreach (var n in names)
        {
            var e = pieces[n]!;
            sb.Append($"        {n} = {{ path = \"{TexturePath}Collection\\\\{n}\", w = {Num(e["w"]!)}, h = {Num(e["h"]!)}, right = {Num(e["right"]!)}, bottom = {Num(e["bottom"]!)} }},\n");
        }

        sb.Append("    },\n}\n");
        return sb.ToString();
    }

    // ---- helpers

    /// <summary>The .blp base names directly in <paramref name="family"/> that the manifest lists, ordinal order.</summary>
    private static List<string> Installed(string root, string family, JsonObject? manifest, List<string>? warnings, string? manifestName)
    {
        var dir = Path.Combine(root, family.Replace('/', Path.DirectorySeparatorChar));
        if (manifest is null || !Directory.Exists(dir))
            return [];
        var result = new List<string>();
        foreach (var file in Directory.EnumerateFiles(dir, "*.blp", SearchOption.TopDirectoryOnly))
        {
            var name = Path.GetFileNameWithoutExtension(file);
            if (manifest.ContainsKey(name))
                result.Add(name);
            else
                warnings?.Add($"{family}/{name}.blp is not in {manifestName}, not listed");
        }

        result.Sort(StringComparer.Ordinal);
        return result;
    }

    private static string? Group(JsonNode? entry) => entry?["group"]?.GetValue<string>();

    private static string Quote(string s) => $"\"{s}\"";

    private static string SetEntry(string s) => $"[\"{s}\"] = true";

    private static string List(IEnumerable<string> keys) => string.Join(", ", keys.Select(Quote));

    /// <summary>A JSON number as Lua source: the shortest text that reads back the same, invariant culture.</summary>
    private static string Num(JsonNode n) => n.GetValueKind() == JsonValueKind.Number
        ? n.GetValue<double>().ToString("R", CultureInfo.InvariantCulture)
        : throw new InvalidDataException($"expected a number, got {n.ToJsonString()}");

    /// <summary>Items <paramref name="perLine"/> to a line, each line indented by 8 and ending in a comma.</summary>
    private static void Chunks(StringBuilder sb, IEnumerable<string> items, int perLine)
    {
        foreach (var chunk in items.Chunk(perLine))
            sb.Append("        ").Append(string.Join(", ", chunk)).Append(",\n");
    }
}
